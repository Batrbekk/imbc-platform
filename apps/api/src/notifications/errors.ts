/**
 * Отказ, который повтор не исправит: нет текста письма или подстановки, неверное задание, неизвестное правило
 * или часть получателей, которой ещё нет. Задание `notify` с таким отказом завершается сразу, со строкой
 * журнала (код правила и причина, без адресов), и не уходит на повторы. Временные сбои (SMTP, база) — обычные
 * ошибки: их повторяет pg-boss. Текст ошибки собирает только код платформы — значений из данных в нём нет.
 */
export class PermanentNotificationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'PermanentNotificationError';
  }
}
