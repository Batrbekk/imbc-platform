/** Подпись типа документа: известные коды переведены, остальные — подпись справочника (MAN-39). */
export function useDocumentLabel(): (type: string) => string {
  const t = useDictionary(texts);
  const items = useProto((s) => s.referenceLists.find((r) => r.id === "document_types")?.items ?? []);
  return (type) =>
    type === "registration_certificate" || type === "charter" || type === "licence"
      ? t(`doc.${type}`)
      : (items.find((i) => i.code === type)?.label ?? type);
}
