import { LPS_TABLE_COLUMNS } from "@imbc/contracts";
import { screen, waitFor, within } from "@testing-library/react";
import { describe, expect, it } from "vitest";
import { LpsPage } from "@/routes/app/lps";
import en from "../messages/en.json";
import ru from "../messages/ru.json";
import kk from "../messages/kk.json";
import { problem } from "./support/api";
import { LPS_ENTRY, lpsList, stubLps } from "./support/lps";
import { renderRoute } from "./support/render";

const routes = [{ path: "/lps", Component: LpsPage }];
function entry() { const value = { ...LPS_ENTRY }; delete (value as Partial<typeof value>).rowNumber; return value; }
const detailPath = `GET /api/v1/lps/entries/${LPS_ENTRY.id}`;
const cases = (["expert", "operator", "director"] as const).flatMap((role) => (["en", "ru", "kk"] as const).map((locale) => ({ role, locale })));
describe("OPR-39 full LPS record reader", () => {
  it.each(cases)("$role can open and close complete readonly details by keyboard in $locale", async ({ role, locale }) => {
    const value = { ...entry(), scopeDescription: "Full current product description\n" + "Long business text. ".repeat(30), newJobs: null };
    const calls = stubLps(role, { [detailPath]: { body: value } });
    const { user, router } = renderRoute("/lps?countryIds=unknown&cities=Demo+city&cities=Other+demo+city&sort=investmentUsd&direction=desc&offset=50", { routes, locale });
    const t = { en, ru, kk }[locale].lps;
    const table = await screen.findByRole("table"), trigger = within(table).getByRole("button", { name: t.openDetails.replace("{company}", LPS_ENTRY.company.name) });
    trigger.focus(); await user.keyboard("{Enter}");
    const dialog = await screen.findByRole("dialog", { name: t.detailsTitle });
    await within(dialog).findByText(/Full current product description/);
    for (const column of LPS_TABLE_COLUMNS) expect(within(dialog).getAllByText(t.columns[column], { selector: "dt" }).length).toBeGreaterThan(0);
    expect(within(dialog).getByText(/Full current product description/).textContent).toBe(value.scopeDescription);
    const amount = within(dialog).getByText(t.columns.investmentUsd, { selector: "dt" }).nextElementSibling?.textContent;
    expect(amount).toBe(locale === "en" ? "9,007,199,254,740,993.12500" : "9\u00a0007\u00a0199\u00a0254\u00a0740\u00a0993,12500");
    expect(within(dialog).getByText("Q2 2028 / Q1 2029")).toBeTruthy();
    const general = within(dialog).getByRole("region", { name: t.contactNumber.replace("{number}", "2") });
    expect(within(general).getByText("general@lps.local")).toBeTruthy();
    expect(within(general).getByText("+70000000002 ext. 001")).toBeTruthy();
    expect(within(general).queryByText("a@lps.local")).toBeNull();
    expect(within(dialog).getByText(t.entryUpdatedAt)).toBeTruthy();
    expect(within(dialog).getByText(t.companyUpdatedAt)).toBeTruthy();
    expect(within(dialog).queryAllByRole("textbox")).toHaveLength(0);
    expect(within(dialog).queryByRole("button", { name: t.edit })).toBeNull();
    expect(within(dialog).queryByRole("button", { name: t.delete })).toBeNull();
    expect(calls.mock.calls.filter(([, init]) => init?.method && init.method !== "GET")).toHaveLength(0);
    const queryBeforeClose = router.state.location.search;
    await user.keyboard("{Escape}");
    await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
    await waitFor(() => expect(document.activeElement).toBe(trigger));
    expect(router.state.location.search).toBe(queryBeforeClose);
    expect(screen.queryByRole("alertdialog")).toBeNull();
    const read = calls.mock.calls.find(([url]) => String(url).includes(`/entries/${LPS_ENTRY.id}?`));
    expect(new URL(String(read![0]), "http://localhost").searchParams.get("locale")).toBe(locale);
  });
  it("unknown/empty groups keep every business label, and reopening reads the current record again", async () => {
    let reads = 0;
    const current = { ...entry(), company: { ...LPS_ENTRY.company, countries: [] }, commodityTypes: [], commodityGroups: [], locations: [], contacts: [], investmentUsd: null, newJobs: null, comment: null, plannedLaunch: null, lastUpdatedOn: null };
    stubLps("operator", { [detailPath]: () => { reads++; return new Response(JSON.stringify({ ...current, scopeDescription: `Current version ${reads}` }), { headers: { "content-type": "application/json" } }); } });
    const { user } = renderRoute("/lps", { routes, locale: "en" });
    const trigger = within(await screen.findByRole("table")).getByRole("button", { name: en.lps.openDetails.replace("{company}", LPS_ENTRY.company.name) });
    await user.click(trigger);
    let dialog = await screen.findByRole("dialog");
    await within(dialog).findByText("Current version 1");
    for (const column of LPS_TABLE_COLUMNS) expect(within(dialog).getByText(en.lps.columns[column], { selector: "dt" })).toBeTruthy();
    expect(within(dialog).getAllByText(en.lps.unknown).length).toBeGreaterThan(2);
    await user.click(within(dialog).getByRole("button", { name: en.lps.close }));
    await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
    await user.click(trigger); dialog = await screen.findByRole("dialog");
    await within(dialog).findByText("Current version 2");
    expect(within(dialog).queryByText("Current version 1")).toBeNull();
    expect(reads).toBe(2);
  });
  it.each([403, 404])("a fresh %i detail failure shows no old table facts; retry is explicit", async (status) => {
    const calls = stubLps("director", { [detailPath]: problem(status, status === 403 ? "forbidden" : "not_found"), "GET /api/v1/lps/entries": { body: lpsList() } });
    const { user } = renderRoute("/lps", { routes, locale: "en" });
    await user.click(within(await screen.findByRole("table")).getByRole("button", { name: en.lps.openDetails.replace("{company}", LPS_ENTRY.company.name) }));
    const dialog = await screen.findByRole("dialog");
    await within(dialog).findByText(status === 403 ? en.lps.errors.forbidden : en.lps.errors.notFound);
    expect(within(dialog).queryByText(LPS_ENTRY.company.name)).toBeNull();
    expect(within(dialog).queryByText(LPS_ENTRY.scopeDescription)).toBeNull();
    await user.click(within(dialog).getByRole("button", { name: en.lps.retry }));
    await waitFor(() => expect(calls.mock.calls.filter(([url]) => String(url).includes(`/entries/${LPS_ENTRY.id}?`))).toHaveLength(2));
  });
});
